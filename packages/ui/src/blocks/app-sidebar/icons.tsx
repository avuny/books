import type * as React from "react"

import { cn } from "@workspace/ui/lib/utils"

/**
 * Inline icons for the block's own chrome, so it works with any icon library
 * (lucide, tabler, hugeicons...) your shadcn setup uses.
 */
export type IconProps = Omit<React.ComponentProps<"svg">, "children">

function Icon({
  className,
  children,
  ...props
}: IconProps & { children: React.ReactNode }) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      className={cn("size-4 shrink-0", className)}
      {...props}
    >
      {children}
    </svg>
  )
}

/** Points to the inline end. Add `rtl:rotate-180` where direction matters. */
export function ChevronRightIcon(props: IconProps) {
  return (
    <Icon {...props}>
      <path d="m9 18 6-6-6-6" />
    </Icon>
  )
}

