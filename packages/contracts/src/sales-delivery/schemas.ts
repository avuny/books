import { z } from "@avuny/zod"
import { UNIT_QUANTITY_PATTERN } from "../unit/constants.js"
import {
  SALES_DELIVERY_CARRIER_MAX_LENGTH,
  SALES_DELIVERY_LINE_NOTES_MAX_LENGTH,
  SALES_DELIVERY_MAX_LINES,
  SALES_DELIVERY_NOTES_MAX_LENGTH,
  SALES_DELIVERY_REASON_MAX_LENGTH,
  SALES_DELIVERY_STATUSES,
  SALES_DELIVERY_TRACKING_MAX_LENGTH,
} from "./constants.js"

const id = z.string().uuid()
const timestamp = z.string().datetime()
const date = z.string().trim().regex(/^\d{4}-\d{2}-\d{2}$/, "Use YYYY-MM-DD")
const quantity = z.string().trim().regex(UNIT_QUANTITY_PATTERN, "Invalid quantity")
const text = (max: number) => z.string().trim().max(max)

export const SalesDeliveryStatusSchema = z.enum(SALES_DELIVERY_STATUSES)

/**
 * One delivered quantity of one sales order line. `locationId` defaults to the order line's location.
 * The batch is never chosen here: posting consumes the order's reservation (FEFO allocations).
 */
export const SalesDeliveryLineInputSchema = z.object({
  salesOrderLineId: id,
  /** Defaults to the order line's unit. */
  unitId: id.nullish(),
  /** Defaults to the order line's location. */
  locationId: id.nullish(),
  quantity,
  notes: text(SALES_DELIVERY_LINE_NOTES_MAX_LENGTH).nullish(),
})
export type SalesDeliveryLineInput = z.infer<typeof SalesDeliveryLineInputSchema>

export const SalesDeliveryLineDtoSchema = z.object({
  id,
  salesDeliveryId: id,
  lineNo: z.number().int(),
  salesOrderLineId: id,
  itemId: id,
  itemName: z.string().nullable().optional(),
  descriptionSnapshot: z.string().nullable(),
  warehouseId: id,
  locationId: id,
  locationName: z.string().nullable().optional(),
  unitId: id,
  unitSymbol: z.string().nullable().optional(),
  baseUnitFactor: z.string(),
  quantity: z.string(),
  baseQuantity: z.string(),
  /** Cost of goods sold for the line in minor units. Zero until the delivery is posted. */
  costAmount: z.string(),
  notes: z.string().nullable(),
})
export type SalesDeliveryLineDto = z.infer<typeof SalesDeliveryLineDtoSchema>

const lines = z
  .array(SalesDeliveryLineInputSchema)
  .min(1, "At least one delivery line is required")
  .max(SALES_DELIVERY_MAX_LINES, `Maximum ${SALES_DELIVERY_MAX_LINES} lines allowed`)

const headerFields = {
  deliveryDate: date,
  carrier: text(SALES_DELIVERY_CARRIER_MAX_LENGTH).nullish(),
  trackingNumber: text(SALES_DELIVERY_TRACKING_MAX_LENGTH).nullish(),
  notes: text(SALES_DELIVERY_NOTES_MAX_LENGTH).nullish(),
}

/** The number is generated by the server. The sales order comes from the path. */
export const CreateSalesDeliverySchema = z.object({ ...headerFields, lines })
export type CreateSalesDeliveryInput = z.infer<typeof CreateSalesDeliverySchema>

export const UpdateSalesDeliverySchema = z
  .object({
    deliveryDate: date.optional(),
    carrier: headerFields.carrier,
    trackingNumber: headerFields.trackingNumber,
    notes: headerFields.notes,
    lines: lines.optional(),
  })
  .refine((v) => Object.keys(v).length > 0, "At least one field must be provided for update")
export type UpdateSalesDeliveryInput = z.infer<typeof UpdateSalesDeliverySchema>

export const ReverseSalesDeliverySchema = z.object({
  reason: text(SALES_DELIVERY_REASON_MAX_LENGTH).min(1, "A reason is required"),
})
export type ReverseSalesDeliveryInput = z.infer<typeof ReverseSalesDeliverySchema>

export const SalesDeliveryDtoSchema = z.object({
  id,
  number: z.string(),
  salesOrderId: id,
  salesOrderNumber: z.string().nullable().optional(),
  partyId: id,
  partyName: z.string().nullable().optional(),
  deliveryDate: z.string(),
  carrier: z.string().nullable(),
  trackingNumber: z.string().nullable(),
  notes: z.string().nullable(),
  status: SalesDeliveryStatusSchema,
  currency: z.string(),
  /** Sum of line cost amounts (cost of goods sold), minor units. Zero until posted. */
  totalCost: z.string(),
  stockMovementId: id.nullable(),
  journalEntryId: id.nullable(),
  postedAt: timestamp.nullable(),
  postedBy: id.nullable(),
  reversedAt: timestamp.nullable(),
  reversedBy: id.nullable(),
  reverseReason: z.string().nullable(),
  createdBy: id.nullable(),
  lines: z.array(SalesDeliveryLineDtoSchema),
  createdAt: timestamp,
  updatedAt: timestamp,
})
export type SalesDeliveryDto = z.infer<typeof SalesDeliveryDtoSchema>

export const SalesDeliveryListResponseSchema = z.object({
  items: z.array(SalesDeliveryDtoSchema),
})
export type SalesDeliveryListResponse = z.infer<typeof SalesDeliveryListResponseSchema>
