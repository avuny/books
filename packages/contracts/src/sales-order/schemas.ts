import { z } from "@avuny/zod"
import { UNIT_QUANTITY_PATTERN } from "../unit/constants.js"
import {
  SALES_ORDER_LINE_DESCRIPTION_MAX_LENGTH,
  SALES_ORDER_LINE_NOTES_MAX_LENGTH,
  SALES_ORDER_LIST_DEFAULT_PAGE_SIZE,
  SALES_ORDER_LIST_MAX_PAGE_SIZE,
  SALES_ORDER_MAX_LINES,
  SALES_ORDER_MAX_RATE_BPS,
  SALES_ORDER_NOTES_MAX_LENGTH,
  SALES_ORDER_REASON_MAX_LENGTH,
  SALES_ORDER_DEFAULT_RESERVATION_POLICY,
  SALES_ORDER_RESERVATION_POLICIES,
  SALES_ORDER_STATUSES,
  SALES_ORDER_CUSTOMER_REFERENCE_MAX_LENGTH,
} from "./constants.js"
import { PaymentTermMethodSchema } from "../payment-term/schemas.js"

const id = z.string().uuid()
const timestamp = z.string().datetime()
const date = z.string().trim().regex(/^\d{4}-\d{2}-\d{2}$/, "Use YYYY-MM-DD")
const quantity = z.string().trim().regex(UNIT_QUANTITY_PATTERN, "Invalid quantity")
/** Integer minor units as a string ("12500" = 125.00 in a two-decimal currency). */
const minorAmount = z.string().trim().regex(/^\d{1,15}$/, "Invalid amount")
/** Rate in basis points (1500 = 15%). */
const rateBps = z.number().int().min(0).max(SALES_ORDER_MAX_RATE_BPS)
const text = (max: number) => z.string().trim().max(max)

export const SalesOrderStatusSchema = z.enum(SALES_ORDER_STATUSES)

/* ---------- line input & dto ---------- */

export const SalesOrderLineInputSchema = z.object({
  itemId: id,
  description: text(SALES_ORDER_LINE_DESCRIPTION_MAX_LENGTH).nullish(),
  /** Defaults to the header warehouse. */
  warehouseId: id.nullish(),
  locationId: id,
  unitId: id,
  orderedQty: quantity,
  unitPrice: minorAmount,
  /** Fixed discount. Use either this or `discountRateBps`, not both. */
  discountAmount: minorAmount.default("0"),
  /** Percent discount in basis points, applied to the gross line amount. */
  discountRateBps: rateBps.default(0),
  /** Tax in basis points, applied to the discounted line amount. */
  taxRateBps: rateBps.default(0),
  requestedDeliveryDate: date.nullish(),
  notes: text(SALES_ORDER_LINE_NOTES_MAX_LENGTH).nullish(),
})
export type SalesOrderLineInput = z.infer<typeof SalesOrderLineInputSchema>

export const SalesOrderLineDtoSchema = z.object({
  id,
  salesOrderId: id,
  lineNo: z.number().int(),
  itemId: id,
  itemName: z.string().nullable().optional(),
  itemSku: z.string().nullable().optional(),
  description: z.string().nullable(),
  warehouseId: id,
  warehouseName: z.string().nullable().optional(),
  locationId: id,
  locationName: z.string().nullable().optional(),
  locationCode: z.string().nullable().optional(),
  unitId: id,
  unitName: z.string().nullable().optional(),
  unitSymbol: z.string().nullable().optional(),
  baseUnitFactor: z.string(),
  orderedQty: z.string(),
  orderedBaseQty: z.string(),
  reservedBaseQty: z.string(),
  deliveredBaseQty: z.string(),
  invoicedBaseQty: z.string(),
  cancelledBaseQty: z.string(),
  /** Derived: ordered - cancelled - delivered. */
  openToDeliverBaseQty: z.string(),
  /** Derived: max(0, openToDeliver - reserved). Backorder demand without stock behind it. */
  unreservedOpenBaseQty: z.string(),
  unitPrice: z.string(),
  discountAmount: z.string(),
  discountRateBps: z.number().int(),
  taxRateBps: z.number().int(),
  lineNetAmount: z.string(),
  taxAmount: z.string(),
  lineTotalAmount: z.string(),
  requestedDeliveryDate: z.string().nullable(),
  notes: z.string().nullable(),
  createdAt: timestamp,
  updatedAt: timestamp,
})
export type SalesOrderLineDto = z.infer<typeof SalesOrderLineDtoSchema>

/* ---------- header input & dto ---------- */

const headerFields = {
  partyId: id,
  orderDate: date,
  requestedDeliveryDate: date.nullish(),
  paymentTermId: id.nullish(),
  warehouseId: id.nullish(),
  customerReference: text(SALES_ORDER_CUSTOMER_REFERENCE_MAX_LENGTH).nullish(),
  notes: text(SALES_ORDER_NOTES_MAX_LENGTH).nullish(),
}

const lines = z
  .array(SalesOrderLineInputSchema)
  .min(1, "At least one order line is required")
  .max(SALES_ORDER_MAX_LINES, `Maximum ${SALES_ORDER_MAX_LINES} lines allowed`)

/** The number is generated by the server and is never accepted from the client. */
export const CreateSalesOrderSchema = z.object({ ...headerFields, lines })
export type CreateSalesOrderInput = z.infer<typeof CreateSalesOrderSchema>

export const UpdateSalesOrderSchema = z
  .object({
    partyId: id.optional(),
    orderDate: date.optional(),
    requestedDeliveryDate: date.nullish(),
    paymentTermId: id.nullish(),
    warehouseId: id.nullish(),
    customerReference: headerFields.customerReference,
    notes: headerFields.notes,
    lines: lines.optional(),
  })
  .refine((v) => Object.keys(v).length > 0, "At least one field must be provided for update")
export type UpdateSalesOrderInput = z.infer<typeof UpdateSalesOrderSchema>

export const SalesOrderDtoSchema = z.object({
  id,
  number: z.string(),
  partyId: id,
  partyName: z.string().nullable().optional(),
  orderDate: z.string(),
  requestedDeliveryDate: z.string().nullable(),
  paymentTermId: id.nullable(),
  paymentTermName: z.string().nullable(),
  paymentTermMethod: PaymentTermMethodSchema.nullable(),
  paymentTermDays: z.number().int().nullable(),
  currency: z.string(),
  warehouseId: id.nullable(),
  warehouseName: z.string().nullable().optional(),
  customerReference: z.string().nullable(),
  notes: z.string().nullable(),
  status: SalesOrderStatusSchema,
  subtotalAmount: z.string(),
  discountAmount: z.string(),
  taxAmount: z.string(),
  totalAmount: z.string(),
  closeReason: z.string().nullable(),
  createdBy: id.nullable(),
  createdByName: z.string().nullable().optional(),
  confirmedAt: timestamp.nullable(),
  confirmedBy: id.nullable(),
  closedAt: timestamp.nullable(),
  cancelledAt: timestamp.nullable(),
  lines: z.array(SalesOrderLineDtoSchema),
  createdAt: timestamp,
  updatedAt: timestamp,
})
export type SalesOrderDto = z.infer<typeof SalesOrderDtoSchema>

/* ---------- actions ---------- */

export const CloseSalesOrderSchema = z.object({
  reason: text(SALES_ORDER_REASON_MAX_LENGTH).min(1, "A reason is required"),
})
export type CloseSalesOrderInput = z.infer<typeof CloseSalesOrderSchema>

export const ConfirmSalesOrderSchema = z.object({
  policy: z.enum(SALES_ORDER_RESERVATION_POLICIES).default(SALES_ORDER_DEFAULT_RESERVATION_POLICY),
})
export type ConfirmSalesOrderInput = z.infer<typeof ConfirmSalesOrderSchema>

export const CancelSalesOrderSchema = z.object({
  reason: text(SALES_ORDER_REASON_MAX_LENGTH).nullish(),
})
export type CancelSalesOrderInput = z.infer<typeof CancelSalesOrderSchema>

/* ---------- number preview ---------- */

export const SalesOrderNumberPreviewDtoSchema = z.object({
  /** Advisory only; the server allocates the authoritative number on save. */
  number: z.string(),
  /** Organization-local today (`YYYY-MM-DD`), for date defaults. Never derive it from UTC. */
  today: z.string(),
  currency: z.string(),
})
export type SalesOrderNumberPreviewDto = z.infer<typeof SalesOrderNumberPreviewDtoSchema>

/* ---------- list ---------- */

export const SalesOrderListItemDtoSchema = z.object({
  id,
  number: z.string(),
  partyId: id,
  partyName: z.string().nullable().optional(),
  orderDate: z.string(),
  requestedDeliveryDate: z.string().nullable(),
  currency: z.string(),
  status: SalesOrderStatusSchema,
  totalAmount: z.string(),
  lineCount: z.number().int(),
  createdAt: timestamp,
  updatedAt: timestamp,
})
export type SalesOrderListItemDto = z.infer<typeof SalesOrderListItemDtoSchema>

export const SalesOrderOffsetListQuerySchema = z.object({
  page: z.coerce.number().int().min(1).default(1),
  pageSize: z.coerce
    .number()
    .int()
    .min(1)
    .max(SALES_ORDER_LIST_MAX_PAGE_SIZE)
    .default(SALES_ORDER_LIST_DEFAULT_PAGE_SIZE),
  search: z.string().trim().max(100).optional(),
  partyId: id.optional(),
  status: SalesOrderStatusSchema.optional(),
  fromDate: date.optional(),
  toDate: date.optional(),
})
export type SalesOrderOffsetListQuery = z.infer<typeof SalesOrderOffsetListQuerySchema>

export const SalesOrderOffsetListResponseSchema = z.object({
  items: z.array(SalesOrderListItemDtoSchema),
  page: z.number().int(),
  pageSize: z.number().int(),
  total: z.number().int(),
})
export type SalesOrderOffsetListResponse = z.infer<typeof SalesOrderOffsetListResponseSchema>
