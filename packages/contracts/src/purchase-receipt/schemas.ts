import { z } from "@avuny/zod"
import { UNIT_QUANTITY_PATTERN } from "../unit/constants.js"
import { addQty, cmpQty, isPositiveQty } from "../purchase-order/rules.js"
import {
  PURCHASE_RECEIPT_LINE_NOTES_MAX_LENGTH,
  PURCHASE_RECEIPT_MAX_LINES,
  PURCHASE_RECEIPT_NOTES_MAX_LENGTH,
  PURCHASE_RECEIPT_REASON_MAX_LENGTH,
  PURCHASE_RECEIPT_REFERENCE_MAX_LENGTH,
  PURCHASE_RECEIPT_REJECTION_REASON_MAX_LENGTH,
  PURCHASE_RECEIPT_STATUSES,
} from "./constants.js"

import { VENDOR_BILL_SUPPLIER_INVOICE_MAX_LENGTH } from "../vendor-bill/constants.js"
import { VendorBillDtoSchema } from "../vendor-bill/schemas.js"
import { VENDOR_PAYMENT_REFERENCE_MAX_LENGTH } from "../vendor-payment/constants.js"
import { VendorPaymentDtoSchema, VendorPaymentMethodSchema } from "../vendor-payment/schemas.js"

const id = z.string().uuid()
const timestamp = z.string().datetime()
const date = z.string().trim().regex(/^\d{4}-\d{2}-\d{2}$/, "Use YYYY-MM-DD")
const quantity = z.string().trim().regex(UNIT_QUANTITY_PATTERN, "Invalid quantity")
const text = (max: number) => z.string().trim().max(max)

export const PurchaseReceiptStatusSchema = z.enum(PURCHASE_RECEIPT_STATUSES)

/**
 * received = accepted + rejected. Accepted goes on hand at `locationId`. Rejected goods are
 * recorded with a reason and never become stock (they are returned or held outside the system).
 * `isDirect` receives against the unshipped quantity without a posted shipment.
 */
export const PurchaseReceiptLineInputSchema = z
  .object({
    purchaseOrderLineId: id,
    unitId: id,
    locationId: id,
    receivedQty: quantity,
    acceptedQty: z.string().trim().regex(/^\d{1,12}(\.\d{1,6})?$/, "Invalid quantity"),
    rejectedQty: z.string().trim().regex(/^\d{1,12}(\.\d{1,6})?$/, "Invalid quantity").default("0"),
    isDirect: z.boolean().default(false),
    batchId: id.nullish(),
    expiresOn: z.string().regex(/^\d{4}-\d{2}-\d{2}$/, "Invalid date").nullish(),
    rejectionReason: text(PURCHASE_RECEIPT_REJECTION_REASON_MAX_LENGTH).nullish(),
    notes: text(PURCHASE_RECEIPT_LINE_NOTES_MAX_LENGTH).nullish(),
  })
  .superRefine((v, ctx) => {
    // Refinements can run after a field failed its pattern: only do quantity math on plain decimals.
    const decimal = /^\d+(\.\d+)?$/
    if (![v.receivedQty, v.acceptedQty, v.rejectedQty].every((q) => decimal.test(q))) return
    if (!isPositiveQty(v.receivedQty)) {
      ctx.addIssue({ code: "custom", path: ["receivedQty"], message: "Received quantity must be greater than zero" })
    }
    if (cmpQty(addQty(v.acceptedQty, v.rejectedQty), v.receivedQty) !== 0) {
      ctx.addIssue({ code: "custom", path: ["receivedQty"], message: "Received must equal accepted plus rejected" })
    }
    if (cmpQty(v.rejectedQty, "0") > 0 && !v.rejectionReason?.trim()) {
      ctx.addIssue({ code: "custom", path: ["rejectionReason"], message: "A rejection reason is required" })
    }
  })
export type PurchaseReceiptLineInput = z.infer<typeof PurchaseReceiptLineInputSchema>

export const PurchaseReceiptLineDtoSchema = z.object({
  id,
  purchaseReceiptId: id,
  lineNo: z.number().int(),
  purchaseOrderLineId: id,
  itemId: id,
  itemName: z.string().nullable().optional(),
  warehouseId: id,
  locationId: id,
  locationName: z.string().nullable().optional(),
  unitId: id,
  unitSymbol: z.string().nullable().optional(),
  baseUnitFactor: z.string(),
  receivedQty: z.string(),
  acceptedQty: z.string(),
  rejectedQty: z.string(),
  receivedBaseQty: z.string(),
  acceptedBaseQty: z.string(),
  rejectedBaseQty: z.string(),
  isDirect: z.boolean(),
  batchId: id.nullable(),
  expiresOn: z.string().nullable(),
  /** PO net price per base unit, in minor units (informational snapshot). */
  unitCostSnapshot: z.string(),
  /** Value of the accepted quantity in minor units: what the cost layer and the journal carry. */
  receiptValue: z.string(),
  rejectionReason: z.string().nullable(),
  notes: z.string().nullable(),
})
export type PurchaseReceiptLineDto = z.infer<typeof PurchaseReceiptLineDtoSchema>

const lines = z
  .array(PurchaseReceiptLineInputSchema)
  .min(1, "At least one receipt line is required")
  .max(PURCHASE_RECEIPT_MAX_LINES, `Maximum ${PURCHASE_RECEIPT_MAX_LINES} lines allowed`)

const headerFields = {
  receiptDate: date,
  supplierDeliveryReference: text(PURCHASE_RECEIPT_REFERENCE_MAX_LENGTH).nullish(),
  notes: text(PURCHASE_RECEIPT_NOTES_MAX_LENGTH).nullish(),
}

/** The number is generated by the server. The purchase order comes from the path. */
export const CreatePurchaseReceiptSchema = z.object({ ...headerFields, lines })
export type CreatePurchaseReceiptInput = z.infer<typeof CreatePurchaseReceiptSchema>

export const UpdatePurchaseReceiptSchema = z
  .object({
    receiptDate: date.optional(),
    supplierDeliveryReference: headerFields.supplierDeliveryReference,
    notes: headerFields.notes,
    lines: lines.optional(),
  })
  .refine((v) => Object.keys(v).length > 0, "At least one field must be provided for update")
export type UpdatePurchaseReceiptInput = z.infer<typeof UpdatePurchaseReceiptSchema>

export const ReversePurchaseReceiptSchema = z.object({
  reason: text(PURCHASE_RECEIPT_REASON_MAX_LENGTH).min(1, "A reason is required"),
})
export type ReversePurchaseReceiptInput = z.infer<typeof ReversePurchaseReceiptSchema>

export const PurchaseReceiptDtoSchema = z.object({
  id,
  number: z.string(),
  purchaseOrderId: id,
  purchaseOrderNumber: z.string().nullable().optional(),
  partyId: id,
  partyName: z.string().nullable().optional(),
  receiptDate: z.string(),
  supplierDeliveryReference: z.string().nullable(),
  notes: z.string().nullable(),
  status: PurchaseReceiptStatusSchema,
  currency: z.string(),
  /** Sum of line receipt values, minor units. */
  totalValue: z.string(),
  stockMovementId: id.nullable(),
  journalEntryId: id.nullable(),
  /** Derived from the posted vendor bills that match this receipt's lines. */
  billStatus: z.enum(["NOT_APPLICABLE", "AWAITING_BILL", "PARTIALLY_BILLED", "BILLED"]),
  postedAt: timestamp.nullable(),
  postedBy: id.nullable(),
  reversedAt: timestamp.nullable(),
  reversedBy: id.nullable(),
  reverseReason: z.string().nullable(),
  createdBy: id.nullable(),
  lines: z.array(PurchaseReceiptLineDtoSchema),
  createdAt: timestamp,
  updatedAt: timestamp,
})
export type PurchaseReceiptDto = z.infer<typeof PurchaseReceiptDtoSchema>

export const PurchaseReceiptListResponseSchema = z.object({
  items: z.array(PurchaseReceiptDtoSchema),
})
export type PurchaseReceiptListResponse = z.infer<typeof PurchaseReceiptListResponseSchema>

/**
 * Quick purchase receipt: receives goods on one purchase order, posts the receipt, bills it, posts the
 * bill and records a posted supplier payment for the full bill total in one step.
 */
export const QuickPurchaseReceiptSchema = z.object({
  receipt: CreatePurchaseReceiptSchema,
  supplierInvoiceNumber: text(VENDOR_BILL_SUPPLIER_INVOICE_MAX_LENGTH).nullish(),
  method: VendorPaymentMethodSchema,
  referenceNumber: text(VENDOR_PAYMENT_REFERENCE_MAX_LENGTH).nullish(),
})
export type QuickPurchaseReceiptInput = z.infer<typeof QuickPurchaseReceiptSchema>

export const QuickPurchaseReceiptDtoSchema = z.object({
  receipt: PurchaseReceiptDtoSchema,
  bill: VendorBillDtoSchema,
  payment: VendorPaymentDtoSchema,
})
export type QuickPurchaseReceiptDto = z.infer<typeof QuickPurchaseReceiptDtoSchema>
