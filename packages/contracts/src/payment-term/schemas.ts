import { z } from "@avuny/zod"
import {
  PAYMENT_TERM_DAYS_MAX,
  PAYMENT_TERM_METHODS,
  PAYMENT_TERM_NAME_MAX_LENGTH,
  PAYMENT_TERM_NAME_MIN_LENGTH,
} from "./constants.js"

const id = z.string().uuid()
const timestamp = z.string().datetime()
const name = z.string().trim().min(PAYMENT_TERM_NAME_MIN_LENGTH).max(PAYMENT_TERM_NAME_MAX_LENGTH)
const days = z.number().int().min(0).max(PAYMENT_TERM_DAYS_MAX)

export const PaymentTermMethodSchema = z.enum(PAYMENT_TERM_METHODS)

export const PaymentTermDtoSchema = z.object({
  id,
  code: z.string(),
  name: z.string(),
  method: PaymentTermMethodSchema,
  days: z.number().int(),
  isSystem: z.boolean(),
  isActive: z.boolean(),
  sortOrder: z.number().int(),
  createdAt: timestamp,
  updatedAt: timestamp,
})
export type PaymentTermDto = z.infer<typeof PaymentTermDtoSchema>

/** Custom terms are created by the user; `code` is generated by the server. */
export const CreatePaymentTermSchema = z.object({
  name,
  method: PaymentTermMethodSchema.default("NET_DAYS"),
  days: days.default(0),
})
export type CreatePaymentTermInput = z.infer<typeof CreatePaymentTermSchema>

export const UpdatePaymentTermSchema = z
  .object({
    name: name.optional(),
    method: PaymentTermMethodSchema.optional(),
    days: days.optional(),
    isActive: z.boolean().optional(),
  })
  .refine((v) => Object.keys(v).length > 0, "At least one field must be provided for update")
export type UpdatePaymentTermInput = z.infer<typeof UpdatePaymentTermSchema>

export const PaymentTermListQuerySchema = z.object({
  includeInactive: z
    .enum(["true", "false"])
    .transform((v) => v === "true")
    .optional(),
})
export type PaymentTermListQuery = z.infer<typeof PaymentTermListQuerySchema>

export const PaymentTermListResponseSchema = z.object({
  items: z.array(PaymentTermDtoSchema),
  max: z.number().int(),
  total: z.number().int(),
})
export type PaymentTermListResponse = z.infer<typeof PaymentTermListResponseSchema>
