import { z } from "@avuny/zod"
import { UNIT_QUANTITY_PATTERN } from "../unit/constants.js"
import {
  PURCHASE_ORDER_LINE_DESCRIPTION_MAX_LENGTH,
  PURCHASE_ORDER_LINE_NOTES_MAX_LENGTH,
  PURCHASE_ORDER_LIST_DEFAULT_PAGE_SIZE,
  PURCHASE_ORDER_LIST_MAX_PAGE_SIZE,
  PURCHASE_ORDER_MAX_LINES,
  PURCHASE_ORDER_MAX_RATE_BPS,
  PURCHASE_ORDER_NOTES_MAX_LENGTH,
  PURCHASE_ORDER_REASON_MAX_LENGTH,
  PURCHASE_ORDER_STATUSES,
  PURCHASE_ORDER_SUPPLIER_REFERENCE_MAX_LENGTH,
} from "./constants.js"
import { PaymentTermMethodSchema } from "../payment-term/schemas.js"

const id = z.string().uuid()
const timestamp = z.string().datetime()
const date = z.string().trim().regex(/^\d{4}-\d{2}-\d{2}$/, "Use YYYY-MM-DD")
const quantity = z.string().trim().regex(UNIT_QUANTITY_PATTERN, "Invalid quantity")
/** Integer minor units as a string ("12500" = 125.00 in a two-decimal currency). */
const minorAmount = z.string().trim().regex(/^\d{1,15}$/, "Invalid amount")
/** Rate in basis points (1500 = 15%). */
const rateBps = z.number().int().min(0).max(PURCHASE_ORDER_MAX_RATE_BPS)
const text = (max: number) => z.string().trim().max(max)

export const PurchaseOrderStatusSchema = z.enum(PURCHASE_ORDER_STATUSES)

/* ---------- line input & dto ---------- */

export const PurchaseOrderLineInputSchema = z.object({
  itemId: id,
  description: text(PURCHASE_ORDER_LINE_DESCRIPTION_MAX_LENGTH).nullish(),
  /** Defaults to the header warehouse. */
  warehouseId: id.nullish(),
  locationId: id,
  unitId: id,
  orderedQty: quantity,
  unitPrice: minorAmount,
  /** Fixed discount. Use either this or `discountRateBps`, not both. */
  discountAmount: minorAmount.default("0"),
  /** Percent discount in basis points, applied to the gross line amount. */
  discountRateBps: rateBps.default(0),
  /** Tax in basis points, applied to the discounted line amount. */
  taxRateBps: rateBps.default(0),
  expectedDeliveryDate: date.nullish(),
  notes: text(PURCHASE_ORDER_LINE_NOTES_MAX_LENGTH).nullish(),
})
export type PurchaseOrderLineInput = z.infer<typeof PurchaseOrderLineInputSchema>

export const PurchaseOrderLineDtoSchema = z.object({
  id,
  purchaseOrderId: id,
  lineNo: z.number().int(),
  itemId: id,
  itemName: z.string().nullable().optional(),
  itemSku: z.string().nullable().optional(),
  description: z.string().nullable(),
  warehouseId: id,
  warehouseName: z.string().nullable().optional(),
  locationId: id,
  locationName: z.string().nullable().optional(),
  locationCode: z.string().nullable().optional(),
  unitId: id,
  unitName: z.string().nullable().optional(),
  unitSymbol: z.string().nullable().optional(),
  baseUnitFactor: z.string(),
  orderedQty: z.string(),
  orderedBaseQty: z.string(),
  shippedBaseQty: z.string(),
  receivedBaseQty: z.string(),
  acceptedBaseQty: z.string(),
  rejectedBaseQty: z.string(),
  invoicedBaseQty: z.string(),
  cancelledBaseQty: z.string(),
  /** Derived: ordered - cancelled - shipped. */
  unshippedBaseQty: z.string(),
  /** Derived: shipped - received. */
  inTransitBaseQty: z.string(),
  unitPrice: z.string(),
  discountAmount: z.string(),
  discountRateBps: z.number().int(),
  taxRateBps: z.number().int(),
  lineNetAmount: z.string(),
  taxAmount: z.string(),
  lineTotalAmount: z.string(),
  expectedDeliveryDate: z.string().nullable(),
  notes: z.string().nullable(),
  createdAt: timestamp,
  updatedAt: timestamp,
})
export type PurchaseOrderLineDto = z.infer<typeof PurchaseOrderLineDtoSchema>

/* ---------- header input & dto ---------- */

const headerFields = {
  partyId: id,
  orderDate: date,
  expectedDeliveryDate: date.nullish(),
  paymentTermId: id.nullish(),
  warehouseId: id.nullish(),
  supplierReference: text(PURCHASE_ORDER_SUPPLIER_REFERENCE_MAX_LENGTH).nullish(),
  notes: text(PURCHASE_ORDER_NOTES_MAX_LENGTH).nullish(),
}

const lines = z
  .array(PurchaseOrderLineInputSchema)
  .min(1, "At least one order line is required")
  .max(PURCHASE_ORDER_MAX_LINES, `Maximum ${PURCHASE_ORDER_MAX_LINES} lines allowed`)

/** The number is generated by the server and is never accepted from the client. */
export const CreatePurchaseOrderSchema = z.object({ ...headerFields, lines })
export type CreatePurchaseOrderInput = z.infer<typeof CreatePurchaseOrderSchema>

export const UpdatePurchaseOrderSchema = z
  .object({
    partyId: id.optional(),
    orderDate: date.optional(),
    expectedDeliveryDate: date.nullish(),
    paymentTermId: id.nullish(),
    warehouseId: id.nullish(),
    supplierReference: headerFields.supplierReference,
    notes: headerFields.notes,
    lines: lines.optional(),
  })
  .refine((v) => Object.keys(v).length > 0, "At least one field must be provided for update")
export type UpdatePurchaseOrderInput = z.infer<typeof UpdatePurchaseOrderSchema>

export const PurchaseOrderDtoSchema = z.object({
  id,
  number: z.string(),
  partyId: id,
  partyName: z.string().nullable().optional(),
  orderDate: z.string(),
  expectedDeliveryDate: z.string().nullable(),
  paymentTermId: id.nullable(),
  paymentTermName: z.string().nullable(),
  paymentTermMethod: PaymentTermMethodSchema.nullable(),
  paymentTermDays: z.number().int().nullable(),
  currency: z.string(),
  warehouseId: id.nullable(),
  warehouseName: z.string().nullable().optional(),
  supplierReference: z.string().nullable(),
  notes: z.string().nullable(),
  status: PurchaseOrderStatusSchema,
  subtotalAmount: z.string(),
  discountAmount: z.string(),
  taxAmount: z.string(),
  totalAmount: z.string(),
  closeReason: z.string().nullable(),
  createdBy: id.nullable(),
  createdByName: z.string().nullable().optional(),
  confirmedAt: timestamp.nullable(),
  confirmedBy: id.nullable(),
  closedAt: timestamp.nullable(),
  cancelledAt: timestamp.nullable(),
  lines: z.array(PurchaseOrderLineDtoSchema),
  createdAt: timestamp,
  updatedAt: timestamp,
})
export type PurchaseOrderDto = z.infer<typeof PurchaseOrderDtoSchema>

/* ---------- actions ---------- */

export const ClosePurchaseOrderSchema = z.object({
  reason: text(PURCHASE_ORDER_REASON_MAX_LENGTH).min(1, "A reason is required"),
})
export type ClosePurchaseOrderInput = z.infer<typeof ClosePurchaseOrderSchema>

export const CancelPurchaseOrderSchema = z.object({
  reason: text(PURCHASE_ORDER_REASON_MAX_LENGTH).nullish(),
})
export type CancelPurchaseOrderInput = z.infer<typeof CancelPurchaseOrderSchema>

/* ---------- number preview ---------- */

export const PurchaseOrderNumberPreviewDtoSchema = z.object({
  /** Advisory only; the server allocates the authoritative number on save. */
  number: z.string(),
  /** Organization-local today (`YYYY-MM-DD`), for date defaults. Never derive it from UTC. */
  today: z.string(),
  currency: z.string(),
})
export type PurchaseOrderNumberPreviewDto = z.infer<typeof PurchaseOrderNumberPreviewDtoSchema>

/* ---------- list ---------- */

export const PurchaseOrderListItemDtoSchema = z.object({
  id,
  number: z.string(),
  partyId: id,
  partyName: z.string().nullable().optional(),
  orderDate: z.string(),
  expectedDeliveryDate: z.string().nullable(),
  currency: z.string(),
  status: PurchaseOrderStatusSchema,
  totalAmount: z.string(),
  lineCount: z.number().int(),
  createdAt: timestamp,
  updatedAt: timestamp,
})
export type PurchaseOrderListItemDto = z.infer<typeof PurchaseOrderListItemDtoSchema>

export const PurchaseOrderOffsetListQuerySchema = z.object({
  page: z.coerce.number().int().min(1).default(1),
  pageSize: z.coerce
    .number()
    .int()
    .min(1)
    .max(PURCHASE_ORDER_LIST_MAX_PAGE_SIZE)
    .default(PURCHASE_ORDER_LIST_DEFAULT_PAGE_SIZE),
  search: z.string().trim().max(100).optional(),
  partyId: id.optional(),
  status: PurchaseOrderStatusSchema.optional(),
  fromDate: date.optional(),
  toDate: date.optional(),
})
export type PurchaseOrderOffsetListQuery = z.infer<typeof PurchaseOrderOffsetListQuerySchema>

export const PurchaseOrderOffsetListResponseSchema = z.object({
  items: z.array(PurchaseOrderListItemDtoSchema),
  page: z.number().int(),
  pageSize: z.number().int(),
  total: z.number().int(),
})
export type PurchaseOrderOffsetListResponse = z.infer<typeof PurchaseOrderOffsetListResponseSchema>
