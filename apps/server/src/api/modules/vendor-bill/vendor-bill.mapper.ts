import type { VendorBillDto, VendorBillLineDto } from "@avuny/contracts"
import type { VendorBillDetailRow, VendorBillLineDetailRow } from "./vendor-bill.types.js"

const toLineDto = (l: VendorBillLineDetailRow): VendorBillLineDto => ({
  id: l.id,
  lineNo: l.lineNo,
  purchaseReceiptLineId: l.purchaseReceiptLineId,
  purchaseReceiptId: l.purchaseReceiptId,
  purchaseReceiptNumber: l.purchaseReceiptNumber ?? null,
  itemId: l.itemId,
  itemName: l.itemName ?? null,
  unitId: l.unitId,
  unitSymbol: l.unitSymbol ?? null,
  description: l.description ?? null,
  billedQty: l.billedQty,
  billedBaseQty: l.billedBaseQty,
  netAmount: String(l.netAmount),
  taxRateBps: l.taxRateBps,
  taxAmount: String(l.taxAmount),
  lineTotal: String(l.lineTotalAmount),
  matchedValue: String(l.matchedValue),
})

export const toVendorBillDto = (r: VendorBillDetailRow, lines: readonly VendorBillLineDetailRow[]): VendorBillDto => ({
  id: r.id,
  number: r.number,
  partyId: r.partyId,
  partyName: r.partyName ?? null,
  supplierInvoiceNumber: r.supplierInvoiceNumber ?? null,
  invoiceDate: r.invoiceDate,
  dueDate: r.dueDate,
  paymentTermId: r.paymentTermId ?? null,
  paymentTermName: r.paymentTermNameSnapshot ?? null,
  notes: r.notes ?? null,
  status: r.status,
  currency: r.currency,
  subtotal: String(r.subtotalAmount),
  taxAmount: String(r.taxAmount),
  total: String(r.totalAmount),
  receivedValue: String(r.receivedValue),
  priceVariance: String(BigInt(r.subtotalAmount) - BigInt(r.receivedValue)),
  journalEntryId: r.journalEntryId ?? null,
  postedAt: r.postedAt?.toISOString() ?? null,
  postedBy: r.postedBy ?? null,
  reversedAt: r.reversedAt?.toISOString() ?? null,
  reversedBy: r.reversedBy ?? null,
  reverseReason: r.reverseReason ?? null,
  createdBy: r.createdBy ?? null,
  lines: [...lines].sort((a, b) => a.lineNo - b.lineNo).map(toLineDto),
  createdAt: r.createdAt.toISOString(),
  updatedAt: r.updatedAt.toISOString(),
})
