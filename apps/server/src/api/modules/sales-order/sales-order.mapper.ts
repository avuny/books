import {
  openToDeliverBaseQty,
  unreservedOpenBaseQty,
  type SalesOrderDto,
  type SalesOrderLineDto,
  type SalesOrderListItemDto,
} from "@avuny/contracts"
import type { SalesOrderDetailRow, SalesOrderLineDetailRow, SalesOrderListRow } from "./sales-order.types.js"

export const toLineDto = (l: SalesOrderLineDetailRow): SalesOrderLineDto => ({
  id: l.id,
  salesOrderId: l.salesOrderId,
  lineNo: l.lineNo,
  itemId: l.itemId,
  itemName: l.itemName ?? null,
  itemSku: null,
  description: l.descriptionSnapshot ?? null,
  warehouseId: l.warehouseId,
  warehouseName: l.warehouseName ?? null,
  locationId: l.locationId,
  locationName: l.locationName ?? null,
  locationCode: l.locationCode ?? null,
  unitId: l.unitId,
  unitName: l.unitName ?? null,
  unitSymbol: l.unitSymbol ?? null,
  baseUnitFactor: l.baseUnitFactorSnapshot,
  orderedQty: l.orderedQty,
  orderedBaseQty: l.orderedBaseQty,
  reservedBaseQty: l.reservedBaseQty,
  deliveredBaseQty: l.deliveredBaseQty,
  invoicedBaseQty: l.invoicedBaseQty,
  cancelledBaseQty: l.cancelledBaseQty,
  openToDeliverBaseQty: openToDeliverBaseQty(l),
  unreservedOpenBaseQty: unreservedOpenBaseQty(l),
  unitPrice: String(l.unitPrice),
  discountAmount: String(l.discountAmount),
  discountRateBps: l.discountRateBps,
  taxRateBps: l.taxRateBps,
  lineNetAmount: String(l.lineNetAmount),
  taxAmount: String(l.taxAmount),
  lineTotalAmount: String(l.lineTotalAmount),
  requestedDeliveryDate: l.requestedDeliveryDate ?? null,
  notes: l.notes ?? null,
  createdAt: l.createdAt.toISOString(),
  updatedAt: l.updatedAt.toISOString(),
})

export const toSalesOrderDto = (
  r: SalesOrderDetailRow,
  lines: readonly SalesOrderLineDetailRow[]
): SalesOrderDto => ({
  id: r.id,
  number: r.number,
  partyId: r.partyId,
  partyName: r.partyName ?? null,
  orderDate: r.orderDate,
  requestedDeliveryDate: r.requestedDeliveryDate ?? null,
  paymentTermId: r.paymentTermId ?? null,
  paymentTermName: r.paymentTermNameSnapshot ?? null,
  paymentTermMethod: r.paymentTermMethodSnapshot ?? null,
  paymentTermDays: r.paymentTermDaysSnapshot ?? null,
  currency: r.currency,
  warehouseId: r.warehouseId ?? null,
  warehouseName: r.warehouseName ?? null,
  customerReference: r.customerReference ?? null,
  notes: r.notes ?? null,
  status: r.status,
  subtotalAmount: String(r.subtotalAmount),
  discountAmount: String(r.discountAmount),
  taxAmount: String(r.taxAmount),
  totalAmount: String(r.totalAmount),
  closeReason: r.closeReason ?? null,
  createdBy: r.createdBy ?? null,
  createdByName: r.createdByName ?? null,
  confirmedAt: r.confirmedAt?.toISOString() ?? null,
  confirmedBy: r.confirmedBy ?? null,
  closedAt: r.closedAt?.toISOString() ?? null,
  cancelledAt: r.cancelledAt?.toISOString() ?? null,
  lines: [...lines].sort((a, b) => a.lineNo - b.lineNo).map(toLineDto),
  createdAt: r.createdAt.toISOString(),
  updatedAt: r.updatedAt.toISOString(),
})

export const toListItemDto = ({ order, partyName, lineCount }: SalesOrderListRow): SalesOrderListItemDto => ({
  id: order.id,
  number: order.number,
  partyId: order.partyId,
  partyName,
  orderDate: order.orderDate,
  requestedDeliveryDate: order.requestedDeliveryDate ?? null,
  currency: order.currency,
  status: order.status,
  totalAmount: String(order.totalAmount),
  lineCount,
  createdAt: order.createdAt.toISOString(),
  updatedAt: order.updatedAt.toISOString(),
})
